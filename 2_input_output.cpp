#include<iostream>
using namespace std;
int main()
{
    int a,b;
    cout<<"enter the value of a: \n";//<< is called insertion operator
    cin>>a;//>>is called extraction operator
    cout<<"enter the value of b: \n";//<< is called insertion operator
    cin>>b;//>>is called extraction operator
    cout<<"the sum is:"<<a+b;
}